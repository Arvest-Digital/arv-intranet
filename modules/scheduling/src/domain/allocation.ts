import { EmployeeId, ProjectId } from '@arv/kernel';
import { Array as Arr, Either, Option, Schema } from 'effect';
import {
  type AllocationRule,
  AllocationRulesBroken,
  AllocationVersionConflict,
  ProjectClosed,
} from './errors';

// ─── Values ──────────────────────────────────────────────────────────────────────────────────

/** A business date with no time, `YYYY-MM-DD` (sad §8). ISO dates compare as plain strings. */
export const IsoDate = Schema.String.pipe(Schema.pattern(/^\d{4}-\d{2}-\d{2}$/));
export type IsoDate = typeof IsoDate.Type;

// TODO(scheduling): T18 owns calendar arithmetic (ticks.ts / capacity.ts); move this there once
// it lands, so the module keeps one date helper.
/** `date` shifted by `days` calendar days. */
export const addDays = (date: IsoDate, days: number): IsoDate => {
  const d = new Date(`${date}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
};

const minDate = (a: IsoDate | null, b: IsoDate | null): IsoDate | null =>
  a === null ? b : b === null ? a : a < b ? a : b;

/** Module-local id of an allocation (UUIDv7, generated by Postgres). */
export const AllocationId = Schema.UUID.pipe(Schema.brand('AllocationId'));
export type AllocationId = typeof AllocationId.Type;

/** `day` / `week` for work (AC-07); `full-day` for leave: each working day takes the full daily capacity (AC-15). */
export const RatePeriod = Schema.Literal('day', 'week', 'full-day');
export type RatePeriod = typeof RatePeriod.Type;

/** Quarter hours are the smallest allocation unit (AC-09). */
export const RATE_STEP_MINUTES = 15;
/** At most 24 hours a day, or 24 hours per working day for a weekly rate (AC-09). */
export const MINUTES_PER_DAY = 24 * 60;

/** An allocation's rate: whole minutes per day or week, or none for a full-day (leave) rate. */
export type Rate =
  | { readonly ratePeriod: 'day' | 'week'; readonly rateMinutes: number }
  | { readonly ratePeriod: 'full-day'; readonly rateMinutes: null };

/** One effective-dated stretch of an allocation, both dates inclusive (ADR-0008). */
export class Segment extends Schema.Class<Segment>('AllocationSegment')({
  startsOn: IsoDate,
  endsOn: IsoDate,
  /** Null only when `ratePeriod` is `full-day`. */
  rateMinutes: Schema.NullOr(Schema.Int),
  ratePeriod: RatePeriod,
}) {}

/**
 * The aggregate root: one identity for history, version and «last changed by» (ADR-0008).
 * Segments are ordered, contiguous and never empty; those ending before today never change (AC-09b).
 */
export class Allocation extends Schema.Class<Allocation>('Allocation')({
  id: AllocationId,
  employeeId: EmployeeId,
  projectId: ProjectId,
  /** Optimistic-concurrency version (AC-07b). */
  version: Schema.Int,
  segments: Schema.NonEmptyArray(Segment),
}) {}

export const ChangeKind = Schema.Literal('created', 'imported', 'changed', 'trimmed', 'removed');
export type ChangeKind = typeof ChangeKind.Type;

/**
 * What a command records in the allocation's history (AC-16). The application adds the
 * allocation, employee and project ids, who made the change and when.
 */
export class HistoryEntry extends Schema.Class<HistoryEntry>('AllocationHistoryEntry')({
  changeKind: ChangeKind,
  /** The first day the change applies to; null for `created`. */
  effectiveFrom: Schema.NullOr(IsoDate),
  /** Segments before the change; null for `created`. */
  before: Schema.NullOr(Schema.Array(Segment)),
  /** Segments after the change; null for `removed`. */
  after: Schema.NullOr(Schema.Array(Segment)),
}) {}

/** A command's result: the segments to store (empty → delete the allocation) and its history entry. */
export interface AllocationUpdate {
  readonly segments: ReadonlyArray<Segment>;
  readonly history: HistoryEntry;
}

// ─── Context the rules are checked against ───────────────────────────────────────────────────

/**
 * The facts a command checks the input against, read by the application from `org` / `projects`
 * and `Today`. A null employment bound or close date means no limit on that side.
 */
export interface BookingContext {
  readonly today: IsoDate;
  readonly employment: { readonly startsOn: IsoDate | null; readonly endsOn: IsoDate | null };
  /** The resource's working days per week, 1–7 (AC-09 weekly limit). */
  readonly workingDaysPerWeek: number;
  /** The project accepts allocations up to and including this date (AC-25); null if no close date. */
  readonly projectCloseDate: IsoDate | null;
}

export type RemovalContext = Pick<BookingContext, 'today' | 'projectCloseDate'>;

type Broken = Either.Either<never, AllocationRulesBroken>;

const broken = (
  rules: ReadonlyArray<AllocationRule>,
  lastBookableDate: IsoDate | null = null,
): Broken =>
  Either.left(
    new AllocationRulesBroken({
      rules: rules as [AllocationRule, ...AllocationRule[]],
      lastBookableDate,
    }),
  );

// ─── Rules ───────────────────────────────────────────────────────────────────────────────────

/** AC-09 hour rules; a full-day rate has no hours to check. */
export const rateRules = (rate: Rate, workingDaysPerWeek: number): AllocationRule[] => {
  if (rate.ratePeriod === 'full-day') return [];
  const minutes = rate.rateMinutes;
  const rules: AllocationRule[] = [];
  if (!(minutes > 0)) rules.push('hours_not_positive');
  if (minutes % RATE_STEP_MINUTES !== 0) rules.push('hours_not_quarter_hour');
  if (rate.ratePeriod === 'day' && minutes > MINUTES_PER_DAY) rules.push('hours_over_24_per_day');
  if (rate.ratePeriod === 'week' && minutes > MINUTES_PER_DAY * workingDaysPerWeek)
    rules.push('hours_over_24_per_working_day');
  return rules;
};

/**
 * The rules a booked stretch `[startsOn, endsOn]` must meet: end not before start, inside the
 * employment period (AC-13, AC-21b) and not past the project's close date (AC-25).
 */
const periodRules = (
  startsOn: IsoDate,
  endsOn: IsoDate,
  ctx: BookingContext,
): { rules: AllocationRule[]; lastBookableDate: IsoDate | null } => {
  const rules: AllocationRule[] = [];
  let lastBookableDate: IsoDate | null = null;
  if (endsOn < startsOn) rules.push('end_before_start');
  const { employment } = ctx;
  if (
    (employment.startsOn !== null && startsOn < employment.startsOn) ||
    (employment.endsOn !== null && endsOn > employment.endsOn)
  ) {
    rules.push('outside_employment_period');
    lastBookableDate = minDate(lastBookableDate, employment.endsOn);
  }
  if (ctx.projectCloseDate !== null && endsOn > ctx.projectCloseDate) {
    rules.push('past_project_close_date');
    lastBookableDate = minDate(lastBookableDate, ctx.projectCloseDate);
  }
  return { rules, lastBookableDate };
};

/** AC-11: a project is open until the end of its close date. */
const checkProjectOpen = (
  projectId: string,
  ctx: RemovalContext,
): Either.Either<void, ProjectClosed> =>
  ctx.projectCloseDate !== null && ctx.projectCloseDate < ctx.today
    ? Either.left(new ProjectClosed({ projectId, closeDate: ctx.projectCloseDate }))
    : Either.right(undefined);

/** AC-07b: the command applies only to the version the user opened. */
const checkVersion = (
  allocation: Allocation,
  expectedVersion: number,
): Either.Either<void, AllocationVersionConflict> =>
  allocation.version === expectedVersion
    ? Either.right(undefined)
    : Either.left(
        new AllocationVersionConflict({
          allocationId: allocation.id,
          expectedVersion,
          currentVersion: allocation.version,
        }),
      );

const sameRate = (a: Segment, b: Rate): boolean =>
  a.ratePeriod === b.ratePeriod && a.rateMinutes === b.rateMinutes;

const rateOf = (segment: Segment): Rate =>
  segment.ratePeriod === 'full-day'
    ? { ratePeriod: 'full-day', rateMinutes: null }
    : { ratePeriod: segment.ratePeriod, rateMinutes: segment.rateMinutes ?? 0 };

const segment = (startsOn: IsoDate, endsOn: IsoDate, rate: Rate): Segment =>
  new Segment({ startsOn, endsOn, rateMinutes: rate.rateMinutes, ratePeriod: rate.ratePeriod });

/** The segments with every day after `lastDay` cut off (the past part when `lastDay` is yesterday). */
const cutAfter = (segments: ReadonlyArray<Segment>, lastDay: IsoDate): Segment[] =>
  segments
    .filter((s) => s.startsOn <= lastDay)
    .map((s) => (s.endsOn <= lastDay ? s : new Segment({ ...s, endsOn: lastDay })));

const firstDay = (allocation: Allocation): IsoDate => allocation.segments[0].startsOn;
const lastDay = (allocation: Allocation): IsoDate => Arr.lastNonEmpty(allocation.segments).endsOn;

// ─── Commands ────────────────────────────────────────────────────────────────────────────────

/** What a new allocation is created from (AC-07, AC-15). */
export type NewAllocationTerms = { readonly startsOn: IsoDate; readonly endsOn: IsoDate } & Rate;

/**
 * Creates an allocation of one segment. Refused when it breaks an AC-09 rule, starts before today
 * (AC-09b), falls outside the employment period (AC-13) or runs past the project's close date;
 * refused as `ProjectClosed` when the project is closed (AC-11). Every broken rule is listed.
 */
export const createAllocation = (
  projectId: ProjectId,
  terms: NewAllocationTerms,
  ctx: BookingContext,
): Either.Either<AllocationUpdate, AllocationRulesBroken | ProjectClosed> =>
  Either.gen(function* () {
    yield* checkProjectOpen(projectId, ctx);
    const period = periodRules(terms.startsOn, terms.endsOn, ctx);
    const rules = [
      ...(terms.startsOn < ctx.today ? (['starts_before_today'] as const) : []),
      ...period.rules,
      ...rateRules(terms, ctx.workingDaysPerWeek),
    ];
    if (rules.length > 0) return yield* broken(rules, period.lastBookableDate);
    const segments = [segment(terms.startsOn, terms.endsOn, terms)];
    return {
      segments,
      history: new HistoryEntry({
        changeKind: 'created',
        effectiveFrom: null,
        before: null,
        after: segments,
      }),
    };
  });

/** A change from today; fields left out keep their current value (contract `AllocationChange`). */
export interface AllocationChangeTerms {
  readonly startsOn?: IsoDate;
  readonly endsOn?: IsoDate;
  readonly rate?: Rate;
}

/**
 * Changes an allocation from today (AC-09b): segments before today keep their hours, the current
 * segment ends yesterday and the new terms run from today. An allocation that has not started yet
 * is replaced whole and may move its start, but not before today. The new terms must meet the
 * AC-09 rules, stay inside the employment period (AC-13: a change that leaves it running past the
 * end date is refused, AC-21b) and not run past the project's close date.
 */
export const changeFromToday = (
  allocation: Allocation,
  expectedVersion: number,
  change: AllocationChangeTerms,
  ctx: BookingContext,
): Either.Either<
  AllocationUpdate,
  AllocationRulesBroken | ProjectClosed | AllocationVersionConflict
> =>
  Either.gen(function* () {
    yield* checkVersion(allocation, expectedVersion);
    yield* checkProjectOpen(allocation.projectId, ctx);
    const { today } = ctx;
    const before = allocation.segments;
    // A finished allocation has nothing from today on to change.
    if (lastDay(allocation) < today) return yield* broken(['ends_before_today']);

    const current = before.find((s) => s.startsOn <= today && today <= s.endsOn) ?? before[0];
    const rate = change.rate ?? rateOf(current);
    const endsOn = change.endsOn ?? lastDay(allocation);
    const started = firstDay(allocation) < today;
    const startsOn = started ? today : (change.startsOn ?? firstDay(allocation));

    const rules: AllocationRule[] = [];
    if (change.startsOn !== undefined && change.startsOn !== firstDay(allocation)) {
      // Moving the start of a running allocation, or of a future one into the past, rewrites the past.
      if (started || change.startsOn < today) rules.push('starts_before_today');
    }
    if (started && endsOn < today) rules.push('ends_before_today');
    const period = periodRules(startsOn, endsOn, ctx);
    // A running allocation's new end before today is already reported as ends_before_today.
    rules.push(...period.rules.filter((r) => !(started && r === 'end_before_start')));
    rules.push(...rateRules(rate, ctx.workingDaysPerWeek));
    if (rules.length > 0) return yield* broken(rules, period.lastBookableDate);

    const yesterday = addDays(today, -1);
    const past = started ? cutAfter(before, yesterday) : [];
    const last = past[past.length - 1];
    // Unchanged hours: the current segment just takes the new end date instead of splitting.
    const segments =
      last !== undefined && last.endsOn === yesterday && sameRate(last, rate)
        ? [...past.slice(0, -1), new Segment({ ...last, endsOn })]
        : [...past, segment(startsOn, endsOn, rate)];
    return {
      segments,
      history: new HistoryEntry({
        changeKind: 'changed',
        effectiveFrom: today,
        before,
        after: segments,
      }),
    };
  });

export type RemovalOutcome = 'ended' | 'deleted';

/**
 * Removes an allocation from today (AC-07a, AC-09b): one that started before today ends yesterday
 * and keeps its past (`ended`); one that starts today or later goes away (`deleted`). Allowed past
 * the employment end date (AC-21b), refused when the project is closed (AC-11).
 */
export const removeFromToday = (
  allocation: Allocation,
  expectedVersion: number,
  ctx: RemovalContext,
): Either.Either<
  AllocationUpdate & { readonly outcome: RemovalOutcome },
  AllocationRulesBroken | ProjectClosed | AllocationVersionConflict
> =>
  Either.gen(function* () {
    yield* checkVersion(allocation, expectedVersion);
    yield* checkProjectOpen(allocation.projectId, ctx);
    const { today } = ctx;
    if (lastDay(allocation) < today) return yield* broken(['ends_before_today']);
    const segments = cutAfter(allocation.segments, addDays(today, -1));
    return {
      outcome: segments.length === 0 ? 'deleted' : 'ended',
      segments,
      history: new HistoryEntry({
        changeKind: 'removed',
        effectiveFrom: today,
        before: allocation.segments,
        after: null,
      }),
    };
  });

/**
 * Ends an allocation on a project's close date (AC-25): segments after `closeDate` are cut off,
 * and an allocation that starts after it is removed. `None` when it already ends by then. The
 * close date is never before today, so the past is never rewritten.
 */
export const trimAt = (
  allocation: Allocation,
  closeDate: IsoDate,
  today: IsoDate,
): Either.Either<Option.Option<AllocationUpdate>, AllocationRulesBroken> =>
  Either.gen(function* () {
    if (closeDate < today) return yield* broken(['close_date_before_today']);
    if (lastDay(allocation) <= closeDate) return Option.none();
    const segments = cutAfter(allocation.segments, closeDate);
    const removed = segments.length === 0;
    return Option.some({
      segments,
      history: new HistoryEntry({
        changeKind: removed ? 'removed' : 'trimmed',
        effectiveFrom: removed ? firstDay(allocation) : addDays(closeDate, 1),
        before: allocation.segments,
        after: removed ? null : segments,
      }),
    });
  });
